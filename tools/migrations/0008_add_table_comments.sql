-- 0008_add_table_comments.sql —— 把 schema 里的表注释 / 字段注释刷进已有库
--
-- 背景：mysql_schema.sql 里的说明文字原先只是文件里的 `--` 行内注释，库里看不到
--   （Navicat 等客户端的表/字段「注释」列全空）。本迁移把注释写进 MySQL 元数据，
--   顺带把列定义对齐到 schema（MODIFY COLUMN 用 schema 里的完整列定义，含 COMMENT）。
-- 幂等性：只跑一次 —— 由执行器（tools/migrate.sh）的记录表保证；本文件不做重复保护。
-- 回滚：无需（注释不影响数据；想改注释就在 schema 改完再加一个新迁移）。
-- ⚠️ 本文件由 schema **一次性生成后冻结**（历史快照）；schema 后续改动注释时，请追加新迁移。

